#!/usr/bin/env node

import { promises as fs } from "node:fs";
import path from "node:path";

const root = process.cwd();
const generatedRoot = path.join(root, "generated", "validohub");
const locales = new Set(["en", "es", "pt-BR", "de", "fr", "pl", "uk"]);
const nonCountrySections = new Set(["tools", "countries", "categories", "identifiers"]);

const forbiddenPatterns = [
  {
    name: "static-engine-footer",
    pattern: /Static tools generated by Valido Engine/i,
  },
  {
    name: "fake-api-preview",
    pattern: /api\.validohub\.com|Developer API Preview|Endpoint shape/i,
  },
  {
    name: "legacy-workbench-heading",
    pattern:
      /<div class="workbench-heading(?: workbench-heading-compact)?">[\s\S]*?(Run the tool|Interactive workbench|Browser workbench)[\s\S]*?<\/div>/i,
  },
  {
    name: "legacy-browser-workbench-copy",
    pattern: /Browser workbench/i,
  },
  {
    name: "intermediate-generic-country-shell",
    pattern: /vh-generic-country-|WHAT THIS TOOL IS FOR|Paste input, choose an action|Browser-only Offline checks|Browser-only checks prove/i,
  },
];

const stats = {
  htmlPages: 0,
  countryToolPages: 0,
  failures: 0,
};

const failures = [];

async function exists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function walk(dir, onFile) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(entryPath, onFile);
    } else if (entry.name === "index.html") {
      await onFile(entryPath);
    }
  }
}

function relativeGeneratedPath(filePath) {
  return path.relative(generatedRoot, filePath).split(path.sep).join("/");
}

function isLocalizedCountryToolPage(filePath, html) {
  const parts = relativeGeneratedPath(filePath).split("/");
  return (
    parts.length === 4 &&
    parts[3] === "index.html" &&
    locales.has(parts[0]) &&
    !nonCountrySections.has(parts[1])
  );
}

function collectForbiddenFailures(rel, html) {
  for (const rule of forbiddenPatterns) {
    if (rule.pattern.test(html)) {
      failures.push({ page: rel, rule: rule.name });
    }
  }
}

async function main() {
  if (!(await exists(generatedRoot))) {
    throw new Error(`Generated root does not exist: ${generatedRoot}`);
  }

  await walk(generatedRoot, async (filePath) => {
    const html = await fs.readFile(filePath, "utf8");
    const rel = relativeGeneratedPath(filePath);
    stats.htmlPages += 1;

    collectForbiddenFailures(rel, html);

    if (isLocalizedCountryToolPage(filePath, html)) {
      stats.countryToolPages += 1;
    }
  });

  stats.failures = failures.length;
  if (failures.length > 0) {
    console.error("✗ Generated premium contract failed");
    console.error(JSON.stringify({ stats, failures: failures.slice(0, 50) }, null, 2));
    process.exit(1);
  }

  console.log("✓ Generated premium contract passed");
  console.log(JSON.stringify(stats, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
